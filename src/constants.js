// ⚠️ ССЫЛКА-ЗАГЛУШКА. QR-код на карточках и приглашения друзьям ведут сюда.
// Замените на реальную страницу установки, когда она появится: ссылку на
// Google Play, лендинг или прямую ссылку на APK. Один раз поменяли здесь —
// обновится везде (карточки, приглашения друзьям).
export const APP_INSTALL_URL = "https://example.com/dkmo";

// Ссылка-приглашение конкретному другу — с его кодом в query-параметре.
// Когда появится реальная страница на APP_INSTALL_URL, добавь на неё
// небольшой JS: читать `ref` из URL (new URLSearchParams(location.search).get("ref"))
// и показывать "Тебя пригласил друг с кодом: XXXXXX" — это резко повышает
// шанс, что новый человек реально введёт код после установки, а не забудет.
export function buildInviteLink(code) {
  return `${APP_INSTALL_URL}?ref=${code}`;
}
